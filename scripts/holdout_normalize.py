#!/usr/bin/env python3
"""Turn the free-text holdout truth (doc/holdout_truth.md, one row per Nr) into the eval format.

Fixed, mechanical rules (no cell is re-judged; the original text stays in doc/holdout_truth.md):
* Website: from data/holdout_keys.json by Nr.
* every field: "nicht prüfbar" stays (cell skipped); text in brackets (…) is a remark and is dropped.
* Firma: the name before the first bracket; "nicht angegeben" (Impressum names no firm) stays
  "nicht angegeben" = correct only if a system returns no Firma (see eval_extraction.correct).
* Verwaltungsart: first word (WEG, Miet, beides); "+ Gewerbe" dropped; "nicht angegeben" -> unbekannt.
* Einheiten: the integer before ":"; "nicht angegeben …" -> keine Angabe.
  Einheiten nur Berlin: "nicht nur Berlin"/"bundesweit"/"deutschlandweit" -> nein, "unklar" -> unklar.
* Ansprechpartner: names separated by "," or ";", remarks in brackets dropped.
* Software: "nicht angegeben …" -> keine; otherwise the names, remarks in brackets dropped.
* Kundenportal, Typ_Verwalter: first word (ja / nein).
Output: doc/holdout_sample.md (untracked: firm and person names).

Usage: python3 scripts/holdout_normalize.py [--truth doc/holdout_truth.md] [--out doc/holdout_sample.md]
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402
from eval_extraction import FIELDS, parse_sample  # noqa: E402

NP = "nicht prüfbar"


def unbracket(s):
    prev = None
    while prev != s:  # nested brackets
        prev, s = s, re.sub(r"\([^()]*\)", "", s)
    return re.sub(r"\s+", " ", s).strip(" ,;")


def norm(field, raw):
    raw = (raw or "").strip()
    low = raw.lower()
    if not raw or low.startswith(NP):
        return NP
    if field == "Firma":
        return "nicht angegeben" if low.startswith("nicht angegeben") else unbracket(raw)
    if field == "Verwaltungsart":
        if low.startswith("nicht angegeben"):
            return "unbekannt"
        w = unbracket(raw).split()[0]
        return {"weg": "WEG", "miet": "Miet", "beides": "beides"}.get(w.lower(), w)
    if field == "Einheiten":
        m = re.match(r"\s*(\d+)\s*:", raw)
        return m.group(1) if m else ("keine Angabe" if low.startswith("nicht angegeben") else raw)
    if field == "Ansprechpartner":
        return ", ".join(n for n in (unbracket(x) for x in re.split(r"[;,]", unbracket(raw))) if n)
    if field == "Software":
        return "keine" if low.startswith("nicht angegeben") else ", ".join(
            n for n in (x.strip() for x in unbracket(raw).split(",")) if n)
    if field in ("Kundenportal", "Typ_Verwalter"):
        return low.split()[0]
    raise KeyError(field)


def berlin_only(raw):
    low = (raw or "").lower()
    if not re.match(r"\s*\d+\s*:", low):
        return ""
    if re.search(r"nicht nur berlin|bundesweit|deutschlandweit", low):
        return "nein"
    return "unklar" if "unklar" in low else "ja"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--truth", default="doc/holdout_truth.md")
    ap.add_argument("--keys", type=Path, default=common.DATA / "holdout_keys.json")
    ap.add_argument("--out", type=Path, default=Path("doc/holdout_sample.md"))
    a = ap.parse_args()
    site_of = {r["Nr"]: r["Website"] for r in json.loads(a.keys.read_text(encoding="utf-8"))["rows"]}
    rows = parse_sample(a.truth)
    cols = ["Nr", "Website"] + FIELDS[:3] + ["Einheiten nur Berlin"] + FIELDS[3:]
    out = ["# Holdout sample, normalised (untracked)", "",
           "Generated by `scripts/holdout_normalize.py` from `doc/holdout_truth.md`; rules in the script.", "",
           "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        rec = {"Nr": r["Nr"], "Website": site_of[r["Nr"]], "Einheiten nur Berlin": berlin_only(r.get("Einheiten"))}
        rec.update({f: norm(f, r.get(f)) for f in FIELDS})
        out.append("| " + " | ".join(str(rec[c]).replace("|", "/") for c in cols) + " |")
    a.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(rows)} Zeilen → {a.out}")


if __name__ == "__main__":
    main()
